function findAnswer(question: string): string {
  const q = question.toLowerCase();
  const matched = Object.entries(TRADING_KB).filter(([key]) =>
    key.split(" ").some((word) => q.includes(word))
  );
  if (matched.length > 0) {
    return matched.map(([, v]) => v).join("\n\n");
  }
  if (q.includes("hello") || q.includes("hi") || q.includes("hey")) {
    return `Hello! I'm Ahmed AI, your trading assistant for Deriv synthetic markets. I can help you with:\n• Trading strategies (Martingale, Fibonacci, D'Alembert)\n• Contract types (Rise/Fall, Over/Under, Accumulators, Matches/Differs)\n• Risk management and position sizing\n• Reading signals and market analysis\n\nWhat would you like to learn today?`;
  }
  if (q.includes("best") && q.includes("strategy")) {
    return "The best strategy depends on your risk tolerance:\n• Low risk: Fixed 1-2% stake, Over/Under or Even/Odd contracts\n• Medium risk: Accumulator contracts, 3-5 tick Rise/Fall\n• High risk: Martingale on Matches/Differs (high reward, can lose fast)\n\nAlways set a daily stop loss and stick to it!";
  }
  if (q.includes("how") && q.includes("signal")) {
    return "AHMED AI signals are generated by analyzing tick frequency distributions:\n1. Collect 100+ ticks per market\n2. Calculate percentage frequency of each digit (0-9)\n3. Identify statistical deviations (>13% or <7%)\n4. Generate contract recommendations with confidence scores\n5. Signals are valid for 20 minutes then regenerate";
  }
  if (q.includes("stop loss") || q.includes("stoploss")) {
    return TRADING_KB["risk management"] + "\n\nCalculate your stop loss:\n• Daily SL = 20% of balance\n• Per-session SL = 10% of balance\n• Per-trade SL = 2% of balance\n\nNever chase losses!";
  }
  return `I don't have specific data on "${question}" yet. Try asking about:\n• Trading strategies (martingale, fibonacci, fixed)\n• Contract types (rise/fall, over/under, even/odd, matches, accumulators)\n• Risk management\n• Volatility/Crash/Boom/Jump indices\n• Reading signals\n\nYou can also upload documents to teach me more!`;
}

function generateFlyerCanvas(signal: {
  type: string; market: string; entry: string; ticks: string; confidence: number; theme: number;
}, logoUrl: string) {
  const W = 800, H = 480;
  const canvas = document.createElement("canvas");
  canvas.width = W; canvas.height = H;
  const ctx = canvas.getContext("2d")!;

  const themes = [
    { bg1: "#000000", bg2: "#001a1a", primary: "#00d1d1", accent: "#00ffff" },
    { bg1: "#0a0020", bg2: "#1a0040", primary: "#f59e0b", accent: "#fde68a" },
    { bg1: "#000000", bg2: "#001200", primary: "#00ff41", accent: "#39ff14" },
    { bg1: "#050012", bg2: "#0d0030", primary: "#a855f7", accent: "#e879f9" },
    { bg1: "#0a0000", bg2: "#200000", primary: "#ef4444", accent: "#f97316" },
  ];
  const t = themes[(signal.theme - 1) % 5];

  const grad = ctx.createLinearGradient(0, 0, W, H);
  grad.addColorStop(0, t.bg1); grad.addColorStop(1, t.bg2);
  ctx.fillStyle = grad; ctx.fillRect(0, 0, W, H);

  ctx.strokeStyle = `${t.primary}22`; ctx.lineWidth = 0.5;
  for (let x = 0; x < W; x += 35) { ctx.beginPath(); ctx.moveTo(x, 0); ctx.lineTo(x, H); ctx.stroke(); }
  for (let y = 0; y < H; y += 35) { ctx.beginPath(); ctx.moveTo(0, y); ctx.lineTo(W, y); ctx.stroke(); }

  ctx.strokeStyle = t.primary; ctx.lineWidth = 3;
  ctx.shadowColor = t.primary; ctx.shadowBlur = 15;
  ctx.strokeRect(10, 10, W - 20, H - 20);
  ctx.shadowBlur = 0;

  const draw = (logoImg: HTMLImageElement | null) => {
    if (logoImg) {
      ctx.save(); ctx.beginPath(); ctx.arc(64, 64, 46, 0, Math.PI * 2); ctx.clip();
      ctx.drawImage(logoImg, 18, 18, 92, 92); ctx.restore();
    }

    ctx.font = "bold 11px monospace"; ctx.fillStyle = t.primary; ctx.letterSpacing = "3px";
    ctx.fillText("AHMED SYNTRADER", 130, 45); ctx.letterSpacing = "0px";
    ctx.font = "bold 28px monospace"; ctx.fillStyle = "#ffffff";
    ctx.fillText("AI SIGNAL FLYER", 130, 82);
    ctx.font = "11px monospace"; ctx.fillStyle = `${t.primary}aa`;
    ctx.fillText(`${CONTACT}  ·  ahmedsyntrader.site`, 130, 105);

    ctx.strokeStyle = `${t.primary}50`; ctx.lineWidth = 1;
    ctx.beginPath(); ctx.moveTo(25, 125); ctx.lineTo(W - 25, 125); ctx.stroke();

    ctx.font = "bold 52px monospace"; ctx.fillStyle = t.primary;
    ctx.shadowColor = t.primary; ctx.shadowBlur = 25;
    ctx.fillText(signal.type, 40, 200); ctx.shadowBlur = 0;

    ctx.font = "15px monospace"; ctx.fillStyle = t.accent;
    ctx.fillText(signal.market.toUpperCase(), W - 200, 160);

    const items = [
      { l: "📌  ENTRY", v: signal.entry },
      { l: "⏱  DURATION", v: signal.ticks },
      { l: "📊  CONFIDENCE", v: `${signal.confidence}%` },
      { l: "⏳  VALID FOR", v: "20 MINUTES" },
    ];
    let ry = 240;
    items.forEach(({ l, v }) => {
      ctx.font = "11px monospace"; ctx.fillStyle = `${t.primary}99`; ctx.fillText(l, 40, ry);
      ctx.font = "bold 15px monospace"; ctx.fillStyle = "#ffffff"; ctx.fillText(v, 40, ry + 20);
      ry += 50;
    });

    ctx.strokeStyle = `${t.primary}40`; ctx.beginPath(); ctx.moveTo(25, H - 65); ctx.lineTo(W - 25, H - 65); ctx.stroke();
    ctx.font = "bold 13px monospace"; ctx.fillStyle = t.primary; ctx.textAlign = "center";
    ctx.fillText(`Made by ${AUTHOR}  ·  ${CONTACT}  ·  ahmedsyntrader.site`, W / 2, H - 38);
    ctx.font = "10px monospace"; ctx.fillStyle = `${t.primary}60`;
    ctx.fillText("Risk Disclaimer: Signals are for educational purposes only. Trade at your own risk.", W / 2, H - 18);
    ctx.textAlign = "left";

    const link = document.createElement("a");
    link.download = `AhmedAI_${signal.type.replace(/\s+/g, "_")}_${Date.now()}.png`;
    link.href = canvas.toDataURL("image/png");
    link.click();
  };

  const img = new window.Image(); img.crossOrigin = "anonymous";
  img.onload = () => draw(img); img.onerror = () => draw(null);
  img.src = logoUrl;
}

